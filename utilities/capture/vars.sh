#!/usr/bin/env bash

# Set to the folder where the archive, prearchive, and other system folders are located.
DATA_ROOT=/data/xnat

# Set to the database name.
PROJECT=xnat

# Set to the server address, e.g. xnatdev.xnat.org, NOT the full URL!
SERVER=xnatdev.xnat.org

# Set to the folder or service name for Tomcat. For example, look under
# /var/lib for tomcat, tomcat7, or tomcat8.
TOMCAT=tomcat7

# Set to the XNAT home folder. This is the same value that's set for xnat.home in Tomcat.
XNAT_HOME=/data/xnat/home

# Set to the XNAT username.
XNAT_USER=xnat

